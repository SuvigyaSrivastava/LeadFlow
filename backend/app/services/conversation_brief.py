HttpClientFactory = Callable[[], httpx.Client]


class LLMProvider:
    mode = "llm"

    def __init__(self, settings: Settings, client_factory: HttpClientFactory | None = None):
        self.name = settings.ai_provider
        self.model = settings.ai_model or DEFAULT_MODELS[self.name]
        self._settings = settings
        self._client_factory = client_factory or (
            lambda: httpx.Client(timeout=settings.ai_timeout_seconds)
        )

    def generate(self, lead: LeadDetail, discussions: list[Discussion]) -> BriefContent:
        prompt = build_user_prompt(lead, discussions)
        try:
            with self._client_factory() as client:
                raw = (
                    self._call_anthropic(client, prompt)
                    if self.name == "anthropic"
                    else (self._call_openai(client, prompt))
                )
        except (httpx.HTTPError, KeyError, IndexError, TypeError, ValueError) as exc:
            # Log the exception type only: messages can echo request content.
            logger.warning("AI provider call failed: %s", type(exc).__name__)
            raise UpstreamError(
                "The AI provider could not be reached or returned an unexpected response. "
                "Nothing was generated. Please try again.",
                code="AI_UPSTREAM_ERROR",
            ) from exc
        try:
            return parse_model_json(raw)
        except (ValueError, ValidationError) as exc:
            logger.warning("AI provider returned unparseable output")
            raise UpstreamError(
                "The AI provider returned a response in an unexpected format. "
                "Nothing was generated. Please try again.",
                code="AI_BAD_RESPONSE",
            ) from exc

    def _call_anthropic(self, client: httpx.Client, prompt: str) -> str:
        base = self._settings.ai_base_url.rstrip("/") or "https://api.anthropic.com"
        response = client.post(
            f"{base}/v1/messages",
            headers={
                "x-api-key": self._settings.ai_api_key,
                "anthropic-version": "2023-06-01",
                "content-type": "application/json",
            },
            json={
                "model": self.model,
                "max_tokens": 1500,
                "system": SYSTEM_PROMPT,
                "messages": [{"role": "user", "content": prompt}],
            },
        )
        response.raise_for_status()
        return "".join(b["text"] for b in response.json()["content"] if b.get("type") == "text")

    def _call_openai(self, client: httpx.Client, prompt: str) -> str:
        base = self._settings.ai_base_url.rstrip("/") or "https://api.openai.com/v1"
        response = client.post(
            f"{base}/chat/completions",
            headers={"authorization": f"Bearer {self._settings.ai_api_key}"},
            json={
                "model": self.model,
                "response_format": {"type": "json_object"},
                "messages": [
                    {"role": "system", "content": SYSTEM_PROMPT},
                    {"role": "user", "content": prompt},
                ],
            },
        )
        response.raise_for_status()
        return response.json()["choices"][0]["message"]["content"]


_SENTENCE_SPLIT = re.compile(r"(?<=[.!?])\s+|\n+")
_INTEREST_RE = re.compile(
    r"\b(interested in|interest in|wants?|wanted|needs?|needed|looking for|looking to|"
    r"priorit\w*|prefers?|preferred|pain points?|concerned|concerns?|goals?)\b",
    re.IGNORECASE,
)
_OPEN_ITEM_RE = re.compile(
    r"\b(will|would|to review|review|follow[- ]?up|pending|waiting|awaiting|send|share|"
    r"schedule|need to|check|confirm|decide|decision|asked|requested|promised)\b",
    re.IGNORECASE,
)


def _sentences(text: str) -> list[str]:
    return [s.strip() for s in _SENTENCE_SPLIT.split(text) if s and s.strip()]


def _shorten(text: str, limit: int = 160) -> str:
    return text if len(text) <= limit else text[: limit - 1].rstrip() + "…"


def _unique(items: list[str], limit: int) -> list[str]:
    seen: set[str] = set()
    out: list[str] = []
    for item in items:
        key = item.lower()
        if key not in seen:
            seen.add(key)
            out.append(item)
        if len(out) == limit:
            break
    return out


class DemoProvider:
    """Deterministic and rule-based. Clearly NOT an AI model."""

    mode = "demo"
    name = "demo"
    model = None

    def generate(self, lead: LeadDetail, discussions: list[Discussion]) -> BriefContent:
        tz = app_tz()
        notes = [(d.created_at.astimezone(tz), d.note) for d in discussions]  # chronological
        first_at, last_at = notes[0][0], notes[-1][0]
        count = len(notes)
        span = (
            f"on {first_at:%d %b %Y}"
            if first_at.date() == last_at.date()
            else f"between {first_at:%d %b %Y} and {last_at:%d %b %Y}"
        )
        summary = (
            f"{count} discussion{'s' if count != 1 else ''} recorded {span}. "
            f"Current status: {lead.status.value}. "
            f"Most recent note: “{_shorten(notes[-1][1], 220)}”"
        )

        interests: list[str] = []
        open_items: list[str] = []
        for _, note in reversed(notes):  # most recent evidence first
            for sentence in _sentences(note):
                if _INTEREST_RE.search(sentence):
                    interests.append(_shorten(sentence))
                if sentence.endswith("?") or _OPEN_ITEM_RE.search(sentence):
                    open_items.append(_shorten(sentence))
        interests = _unique(interests, 5)
        open_items = _unique(open_items, 5)

        for follow_up in lead.pending_follow_ups:
            open_items.append(f"Follow-up scheduled for {_local_label(follow_up.scheduled_at)}")

        questions = [f"Is there any update on: “{_shorten(i, 100)}”?" for i in open_items[:3]]
        questions += [
            "What would a good outcome of the next step look like for you?",
            "Is anyone else involved in this decision who we should include?",
        ]

        first_name = lead.name.split()[0]
        draft = (
            f"Hi {first_name},\n\n"
            f"Thank you for your time when we last spoke ({last_at:%d %b %Y}). "
            "I wanted to follow up and see whether you have any questions or updates "
            "since then.\n\n"
            "[Add specifics from your notes before sending]\n\n"
            "Best regards,\n[Your name]"
        )
        return BriefContent(
            summary=summary,
            recorded_interests=interests,
            open_items=open_items,
            suggested_questions=questions,
            draft_message=draft,
        )


def get_provider(settings: Settings, client_factory: HttpClientFactory | None = None):
    if settings.ai_provider == "demo":
        return DemoProvider()
    if settings.ai_provider in ("anthropic", "openai"):
        if not settings.ai_api_key:
            raise UnavailableError(
                f"AI_PROVIDER is '{settings.ai_provider}' but AI_API_KEY is not set. "
                "Set a key or use AI_PROVIDER=demo.",
                code="AI_UNAVAILABLE",
            )
        return LLMProvider(settings, client_factory)
    raise UnavailableError(
        "The conversation brief is switched off (AI_PROVIDER=none).", code="AI_UNAVAILABLE"
    )


def ai_mode(settings: Settings) -> str:
    if settings.ai_provider == "demo":
        return "demo"
    if settings.ai_provider in ("anthropic", "openai") and settings.ai_api_key:
        return "llm"
    return "unavailable"


def generate_brief(
    db: Session,
    lead_id,
    settings: Settings,
    now: datetime,
    client_factory: HttpClientFactory | None = None,
) -> ConversationBrief:
    lead = leads_service.get_lead_detail(db, lead_id, now)  # 404 if missing
    provider = get_provider(settings, client_factory)

    discussions = list(
        db.scalars(
            select(Discussion)
            .where(Discussion.lead_id == lead_id)
            .order_by(Discussion.created_at, Discussion.id)
        )
    )
    if not discussions:
        raise AppError(
            "There are no recorded discussions for this lead yet. "
            "Log a discussion first so the brief has something to work from.",
            code="NO_DISCUSSIONS",
        )

    content = provider.generate(lead, discussions)
    return ConversationBrief(
        **content.model_dump(),
        mode=provider.mode,
        provider=provider.name,
        model=provider.model,
        generated_at=now,
        discussion_count=len(discussions),
        notice=LLM_NOTICE if provider.mode == "llm" else DEMO_NOTICE,
    )
