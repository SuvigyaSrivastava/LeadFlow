"""'Prepare for Next Conversation' brief.

A small provider interface with three implementations:

* LLMProvider   - Anthropic or OpenAI-compatible HTTP API (real model call)
* demo          - deterministic, rule-based extraction from the recorded notes.
                  Always labelled as demo mode; no model is called.
* unavailable   - AI_PROVIDER=none, or a real provider without a key (HTTP 503).

If a real model call fails we surface an error. We never fall back to an invented
or demo brief behind the user's back.
"""

